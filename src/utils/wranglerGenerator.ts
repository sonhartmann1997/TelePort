import JSZip from 'jszip';
import { WorkerEnvVar } from '../types/worker';

export interface WranglerConfigOptions {
  name: string;
  compatibilityDate?: string;
  hasKv: boolean;
  kvNamespaceName?: string;
  kvNamespaceId?: string;
  envVars: WorkerEnvVar[];
  nodejsCompat?: boolean;
}

export function generateWranglerToml(options: WranglerConfigOptions): string {
  const {
    name = 'teleport',
    compatibilityDate = '2026-11-03',
    hasKv = true,
    kvNamespaceName = 'MOVIE_SAVED',
    kvNamespaceId = '12475ed9f06b4899bc2930d1a7de0ba9',
    envVars = [],
    nodejsCompat = true,
  } = options;

  let toml = `# Cloudflare Worker Configuration
# Generated by Cloudflare Worker Studio
name = "${name.toLowerCase().replace(/[^a-z0-9-_]/g, '-')}"
main = "worker.js"
compatibility_date = "${compatibilityDate}"
`;

  if (nodejsCompat) {
    toml += `compatibility_flags = ["nodejs_compat"]\n`;
  }

  // Non-secret vars
  const plainVars = envVars.filter((v) => !v.isSecret && v.key.trim());
  if (plainVars.length > 0) {
    toml += `\n[vars]\n`;
    for (const v of plainVars) {
      toml += `${v.key} = "${v.value.replace(/"/g, '\\"')}"\n`;
    }
  }

  // D1 Database
  toml += `\n[[d1_databases]]
binding = "DB"
database_name = "teleport-db"
database_id = "5a29a16f-663f-4392-85b8-461a15753829"
`;

  // KV Namespaces
  if (hasKv) {
    toml += `\n[[kv_namespaces]]
binding = "${kvNamespaceName}"
id = "${kvNamespaceId}"
`;
  }

  return toml;
}

export function generateWorkerPackageJson(workerName: string): string {
  return JSON.stringify(
    {
      name: workerName.toLowerCase().replace(/[^a-z0-9-_]/g, '-'),
      version: '1.0.0',
      description: 'Cloudflare Worker serverless microservice',
      main: 'src/worker.js',
      scripts: {
        dev: 'wrangler dev',
        deploy: 'wrangler deploy',
        tail: 'wrangler tail',
      },
      devDependencies: {
        wrangler: '^3.100.0',
      },
    },
    null,
    2
  );
}

export function generateReadme(workerName: string, hasKv: boolean): string {
  return `# ${workerName}

Serverless edge worker built for the Cloudflare global network.

## Quick Start Guide

### 1. Prerequisites
Ensure you have Node.js 18+ installed and a Cloudflare account.

\`\`\`bash
npm install
\`\`\`

### 2. Local Development
Run the local Cloudflare Worker development server with Miniflare:

\`\`\`bash
npx wrangler dev
\`\`\`

This spins up a local edge simulator on \`http://localhost:8787\` with simulated KV and request.cf properties.

${
  hasKv
    ? `### 3. Create KV Namespace (Optional for Remote Deploy)
\`\`\`bash
npx wrangler kv:namespace create MY_KV
\`\`\`
Copy the generated \`id\` into \`wrangler.toml\`.
`
    : ''
}

### 4. Deploy to Cloudflare Network
Authenticate and deploy worldwide across 300+ data centers in seconds:

\`\`\`bash
npx wrangler login
npx wrangler deploy
\`\`\`

### 5. Live Edge Logging
Stream real-time console logs and traces from live production traffic:

\`\`\`bash
npx wrangler tail
\`\`\`
`;
}

export async function createWorkerZip(
  workerCode: string,
  options: WranglerConfigOptions
): Promise<Blob> {
  const zip = new JSZip();

  // Add files
  zip.file('src/worker.js', workerCode);
  zip.file('wrangler.toml', generateWranglerToml(options));
  zip.file('package.json', generateWorkerPackageJson(options.name));
  zip.file('README.md', generateReadme(options.name, options.hasKv));

  return await zip.generateAsync({ type: 'blob' });
}
